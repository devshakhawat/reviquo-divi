<?php // phpcs:ignore
/**
 * Generate the Elegant Themes Marketplace plugin bootstrap from the source bootstrap.
 *
 * The marketplace edition used to ship a hand-maintained copy of
 * product-reviews.php. The two files drifted: the copy sat a version behind and
 * was the only edition declaring WooCommerce HPOS compatibility. This generator
 * removes that class of bug by deriving the marketplace bootstrap from the
 * source on every build.
 *
 * Two transformations are applied:
 *
 *   1. The edition seam - the single `require_once .../licensing.php` line
 *      carrying the `sktpr:edition-seam` marker - is replaced by the
 *      SKTPR_MARKETPLACE_BUILD define, so the package never loads Freemius.
 *   2. Header fields listed in marketplace/manifest.json are overridden.
 *
 * Usage: php bin/make-marketplace-bootstrap.php <source.php> <destination.php>
 *
 * @package Sktpr_Customer_Review
 */

// phpcs:disable WordPress.Security.EscapeOutput.OutputNotEscaped

/**
 * Abort with a message on stderr.
 *
 * @param string $message Reason for aborting.
 * @return void
 */
function sktpr_bootstrap_fail( $message ) {
	fwrite( STDERR, "make-marketplace-bootstrap: {$message}\n" );
	exit( 1 );
}

$source_path = $argv[1] ?? '';
$target_path = $argv[2] ?? '';

if ( '' === $source_path || '' === $target_path ) {
	sktpr_bootstrap_fail( 'usage: make-marketplace-bootstrap.php <source.php> <destination.php> [manifest.json]' );
}

if ( ! is_readable( $source_path ) ) {
	sktpr_bootstrap_fail( "cannot read source bootstrap '{$source_path}'." );
}

$manifest_path = $argv[3] ?? __DIR__ . '/../marketplace/manifest.json';
$manifest      = json_decode( (string) file_get_contents( $manifest_path ), true ); // phpcs:ignore WordPress.WP.AlternativeFunctions

if ( ! is_array( $manifest ) || ! isset( $manifest['header'] ) || ! is_array( $manifest['header'] ) ) {
	sktpr_bootstrap_fail( "marketplace/manifest.json is missing or has no 'header' object." );
}

$source = (string) file_get_contents( $source_path ); // phpcs:ignore WordPress.WP.AlternativeFunctions

/*
 * 1. Swap the edition seam for the marketplace define.
 *
 * The marker must appear exactly once. Matching on the marker rather than on
 * the Freemius code itself means a future refactor of the licensing bootstrap
 * cannot silently produce a marketplace package that still loads Freemius: if
 * the seam moves or disappears, the build stops here.
 */
$seam_pattern = '/^\/\/ sktpr:edition-seam:start\R.*?^\/\/ sktpr:edition-seam:end$/ms';
$seam_count   = preg_match_all( $seam_pattern, $source );

if ( 1 !== $seam_count ) {
	sktpr_bootstrap_fail(
		sprintf(
			'expected exactly one sktpr:edition-seam:start/end region in %s, found %d. Restore the markers or update this generator.',
			basename( $source_path ),
			$seam_count
		)
	);
}

$replacement = "/**\n"
	. " * Marketplace edition marker.\n"
	. " *\n"
	. " * Generated by bin/make-marketplace-bootstrap.php. This edition ships every\n"
	. " * feature and contains no licensing SDK, updater, telemetry or upgrade prompts;\n"
	. " * Features::has_pro_license() reads this constant and returns true.\n"
	. " */\n"
	. "define( 'SKTPR_MARKETPLACE_BUILD', true );";

$generated = preg_replace( $seam_pattern, addcslashes( $replacement, '\\$' ), $source, 1 );

if ( null === $generated ) {
	sktpr_bootstrap_fail( 'the edition seam could not be replaced.' );
}

/*
 * 2. Apply the header overrides.
 *
 * Only the first docblock is touched, which is the WordPress plugin header.
 * Existing fields are rewritten in place; new fields are appended after the
 * last recognised header field so the header keeps a sensible order.
 */
$header_end = strpos( $generated, ' */' );

if ( false === $header_end ) {
	sktpr_bootstrap_fail( 'the plugin header docblock could not be located.' );
}

$header = substr( $generated, 0, $header_end );
$rest   = substr( $generated, $header_end );

foreach ( $manifest['header'] as $field => $value ) {
	$field_pattern = '/^(\s*\*\s*' . preg_quote( $field, '/' ) . ':\s*).*$/m';

	if ( preg_match( $field_pattern, $header ) ) {
		$header = preg_replace_callback(
			$field_pattern,
			static function ( $matches ) use ( $value ) {
				return $matches[1] . $value;
			},
			$header,
			1
		);
		continue;
	}

	// Append after the final `* Key: value` line in the header.
	if ( ! preg_match_all( '/^\s*\*\s*[A-Za-z][A-Za-z ]*:\s*.*$/m', $header, $matches, PREG_OFFSET_CAPTURE ) ) {
		sktpr_bootstrap_fail( 'the plugin header contains no recognisable fields.' );
	}

	$last        = end( $matches[0] );
	$insert_at   = $last[1] + strlen( $last[0] );
	$header      = substr( $header, 0, $insert_at ) . "\n * {$field}: {$value}" . substr( $header, $insert_at );
}

$generated = $header . $rest;

/*
 * 3. Refuse to emit a bootstrap that still references the licensing SDK.
 *
 * build-marketplace.sh runs the same class of check over the whole staged
 * package; repeating it here reports the problem against the file that caused
 * it, before the package is assembled.
 */
if ( preg_match( '/pr_fs\s*\(|freemius|fs_dynamic_init/i', $generated, $leak ) ) {
	sktpr_bootstrap_fail( "the generated bootstrap still references the licensing SDK ('{$leak[0]}')." );
}

if ( false === strpos( $generated, "define( 'SKTPR_MARKETPLACE_BUILD', true );" ) ) {
	sktpr_bootstrap_fail( 'the generated bootstrap does not define SKTPR_MARKETPLACE_BUILD.' );
}

if ( false === file_put_contents( $target_path, $generated ) ) { // phpcs:ignore WordPress.WP.AlternativeFunctions
	sktpr_bootstrap_fail( "could not write '{$target_path}'." );
}

echo "Generated marketplace bootstrap: {$target_path}\n";
